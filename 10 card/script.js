function heroFunction(){
  var sum=''
  users.forEach(function(elem,idx){
    sum+=`<div id="cards">

      <img class="img-bg" src=${elem.bgImage}>
      <img class="img-profile" src=${elem.image}>
      <h2>${elem.fullName}</h2>
      <h4>${elem.designation}</h4>
      <p>Age: ${elem.age}</p>
      <p>Company: ${elem.company}</p>
      <p>Skills: ${elem.skills.join(", ")}</p>
      
      <div class="Profile-details" id="Profile-${idx}" hidden>
      <img class="detail-image" src="${elem.image}" alt="${elem.fullName}">
      <p><b>Full Name: </b> ${elem.fullName}</p>
      <p><b>Designation: </b>${elem.designation}</p>
      <p><b>Company: </b>${elem.company}</p>
      <p><b>All Skills: </b>${elem.skills.join(",")}</p>
      <p><b>Experience: </b>Explore this user's professional profile</p>
      </div>
      <div class="button">
        <button class="view-Profile" data-id="${idx}">View Profile</button>
      </div>
    </div>`
  })
main.innerHTML=sum
}
heroFunction()
